#!/usr/bin/env python3
"""Builds docs/TRACEABILITY.md: requirement -> code -> tests. Exits 1 on gaps.

Gaps: an Implemented requirement with no code or no test, or code/tests citing an ID missing from SPEC.md.
Code is marked with @implements(...) or @mutation(action, ...); tests with @covers(...).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.trace import implements  # noqa: E402
ID = re.compile(r"REQ-[A-Z]+-\d+")
ROW = re.compile(r"^\|\s*(REQ-[A-Z]+-\d+)\s*\|\s*(.*?)\s*\|\s*(P\d)\s*\|\s*(\w+)\s*\|\s*$")


def spec():
    out = {}
    for line in (ROOT / "SPEC.md").read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            out[m[1]] = {"text": m[2], "priority": m[3], "status": m[4]}
    return out


def scan(folder: str, marker: str):
    refs = {}
    for path in sorted((ROOT / folder).glob("*.py")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if line.strip().startswith(marker):
                ids = ID.findall(line)
                name = next((m[1] for l in lines[i + 1 : i + 6] if (m := re.match(r"\s*(?:async\s+)?def (\w+)", l))), "?")
                for rid in ids:
                    refs.setdefault(rid, []).append(f"{path.name}:{name}")
    return refs


@implements("REQ-TRC-04")
def main() -> int:
    reqs = spec()
    code = {}
    for folder in ("app", "scripts"):
        for marker in ("@implements(", "@mutation("):
            for k, v in scan(folder, marker).items():
                code.setdefault(k, []).extend(v)
    tests = scan("tests", "@covers(")
    problems = []
    rows = ["# Traceability matrix", "", "Generated by `python scripts/trace_matrix.py`. Do not edit by hand.", "", "| Requirement | Status | Code | Tests |", "| --- | --- | --- | --- |"]
    for rid, info in sorted(reqs.items()):
        c, t = sorted(set(code.get(rid, []))), sorted(set(tests.get(rid, [])))
        rows.append(f"| {rid} | {info['status']} | {', '.join(c) or '-'} | {', '.join(t) or '-'} |")
        if info["status"] == "Implemented":
            if not c:
                problems.append(f"{rid}: Implemented but no code marked with it")
            if not t:
                problems.append(f"{rid}: Implemented but no test covers it")
    for source, refs in (("code", code), ("tests", tests)):
        for rid in refs:
            if rid not in reqs:
                problems.append(f"{rid}: cited by {source} but not defined in SPEC.md")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "TRACEABILITY.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    done = sum(1 for r in reqs.values() if r["status"] == "Implemented")
    print(f"{len(reqs)} requirements, {done} implemented, {len(reqs) - done} planned")
    for p in problems:
        print("GAP:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
